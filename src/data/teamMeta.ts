export function leagueName(l: LeagueMeta, locale: HubLocale): string {
  return typeof l.name === "string" ? l.name : l.name[locale];
}

export function leagueOfTeam(teamKey: string): LeagueMeta | undefined {
  const slug = TEAM_LEAGUE[teamKey];
  return slug ? LEAGUES.find((l) => l.slug === slug) : undefined;
}

export function leaguesOfCountry(country: string): LeagueMeta[] {
  return LEAGUES.filter((l) => l.country === country);
}

